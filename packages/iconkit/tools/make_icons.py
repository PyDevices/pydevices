"""Build an iconkit module: Material Design icons as antialiased 8-bit alpha masks.

Reads the icons' PNGs from a checkout of google/material-design-icons, keeps
each PNG's alpha channel and writes one Python module whose ``DATA`` holds
every icon's mask end to end. Frozen into firmware, the module stays in flash.

The checkout is a required argument. To fetch only the icons you need, see
the README's "Fetch only the icons you need".

Example::

    python tools/make_icons.py SOURCE --size 24 \\
        --names-file lib/iconkit/icons_24.txt --out lib/iconkit/_a8_24.py --budget 72k

    python tools/make_icons.py SOURCE --size 24 --names home,wifi --out myicons.py

The module's ``NAMES`` is sorted, and icon *i* is
``DATA[i * SIZE * SIZE:(i + 1) * SIZE * SIZE]``.
"""

import argparse
import difflib
import os
import shutil
import sys

from PIL import Image

FETCH_HINT = (
    "Fetch only the icons you need with a sparse checkout; the iconkit README "
    "(\"Fetch only the icons you need\") has the commands. A full clone of https://github.com/google/material-design-icons works too."
)

HEADER = '''\
# SPDX-FileCopyrightText: Google LLC
#
# SPDX-License-Identifier: Apache-2.0
"""Material Design icons, filled style, %(size)d px, as 8-bit alpha masks.

Generated by tools/make_icons.py from google/material-design-icons: do not
edit. The icons are Google's, under the Apache License 2.0.
"""

SIZE = %(size)d
'''


class IconError(Exception):
    """A request the generator can't fulfil; the message says how to fix it."""


def parse_budget(text):
    """Bytes in a budget such as ``72k`` (1024 bytes each), ``2m`` or ``73728``."""
    t = text.strip().lower()
    scale = 1
    if t.endswith("k"):
        scale, t = 1024, t[:-1]
    elif t.endswith("m"):
        scale, t = 1024 * 1024, t[:-1]
    if not t.isdigit():
        raise IconError("budget %r is not a number of bytes (try 72k or 73728)" % (text,))
    return int(t) * scale


def read_names(names_file, names_arg):
    """The icon names from a list file (one per line, ``#`` comments) and a comma list."""
    names = []
    if names_file:
        try:
            with open(names_file, encoding="utf-8") as f:
                lines = f.read().splitlines()
        except OSError as e:
            raise IconError("cannot read names file %r: %s" % (names_file, e)) from None
        for line in lines:
            line = line.split("#", 1)[0].strip()
            if line:
                names.append(line)
    if names_arg:
        names.extend(n.strip() for n in names_arg.split(",") if n.strip())
    if not names:
        raise IconError("no icon names: pass --names a,b,c or --names-file FILE")
    dupes = sorted({n for n in names if names.count(n) > 1})
    if dupes:
        raise IconError("icon names listed more than once: %s" % ", ".join(dupes))
    return sorted(names)


def check_source(source, size):
    """Raise unless *source* is a material-design-icons checkout with *size* px PNGs."""
    png = os.path.join(source, "png")
    if not os.path.isdir(source):
        raise IconError("icon source %r is not a folder. %s" % (source, FETCH_HINT))
    if not os.path.isdir(png):
        raise IconError(
            "%r has no png/ folder, so it is not a material-design-icons checkout. %s" % (source, FETCH_HINT)
        )
    sizes = set()
    have = False
    for cat in os.listdir(png):
        cdir = os.path.join(png, cat)
        if not os.path.isdir(cdir):
            continue
        for name in os.listdir(cdir):
            base = os.path.join(cdir, name, "materialicons")
            if os.path.isdir(base):
                for d in os.listdir(base):
                    if d.endswith("dp"):
                        sizes.add(d[:-2])
                if os.path.isdir(os.path.join(base, "%ddp" % size, "1x")):
                    have = True
                    break
        if have:
            break
    if not have:
        raise IconError(
            "%r has no %ddp icons (sizes found: %s). %s Add the %ddp folders to the sparse checkout."
            % (source, size, ", ".join(sorted(sizes, key=int)) or "none", FETCH_HINT, size)
        )


def find_icon(source, name, size):
    """The PNG path of filled icon *name* at *size* px, in whichever category holds it."""
    png = os.path.join(source, "png")
    found = []
    others = set()
    for cat in sorted(os.listdir(png)):
        base = os.path.join(png, cat, name, "materialicons")
        if os.path.isdir(base):
            path = os.path.join(base, "%ddp" % size, "1x", "baseline_%s_black_%ddp.png" % (name, size))
            if os.path.isfile(path):
                found.append(path)
            else:
                others.update(d for d in os.listdir(base) if d.endswith("dp"))
    if len(found) > 1:
        raise IconError("icon %r is in several categories: %s" % (name, ", ".join(found)))
    if found:
        return found[0]
    if others:
        raise IconError(
            "icon %r has no %ddp PNG here (sizes present: %s). Add the %ddp folders to the sparse "
            "checkout, or pick another size." % (name, size, ", ".join(sorted(others)), size)
        )
    every = set()
    for cat in os.listdir(png):
        cdir = os.path.join(png, cat)
        if os.path.isdir(cdir):
            every.update(os.listdir(cdir))
    close = difflib.get_close_matches(name, sorted(every), n=5)
    raise IconError(
        "icon %r not found in the source. Closest names: %s. Names are the folder names under "
        "png/<category>/; if the checkout is a sparse one, add the icon to it."
        % (name, ", ".join(close) or "none")
    )


def alpha_mask(path, size):
    """The antialiased shape of the PNG at *path* as ``size * size`` bytes."""
    with Image.open(path) as im:
        if im.size != (size, size):
            raise IconError("%s is %dx%d, expected %dx%d" % (path, im.size[0], im.size[1], size, size))
        if im.mode not in ("LA", "RGBA", "PA", "La", "RGBa"):
            raise IconError("%s has mode %s and no alpha channel to take the shape from" % (path, im.mode))
        return im.convert("RGBA").getchannel("A").tobytes()


def literal(data):
    """*data* as a double-quoted bytes literal."""
    out = []
    for b in data:
        if 32 <= b < 127 and b not in (34, 92):
            out.append(chr(b))
        else:
            out.append("\\x%02x" % b)
    return 'b"' + "".join(out) + '"'


def render(size, names, masks):
    """The text of the module for *names* and their *masks*."""
    lines = [HEADER % {"size": size}]
    lines.append("NAMES = (")
    for n in names:
        lines.append('    "%s",' % n)
    lines.append(")")
    lines.append("")
    lines.append("# Adjacent literals join into one constant, so frozen it is one blob in flash.")
    lines.append("DATA = memoryview(")
    for n, m in zip(names, masks):
        lines.append("    # " + n)
        lines.append("    " + literal(m))
    lines.append(")")
    return "\n".join(lines) + "\n"


def build(source, size, names, out, budget=None, license_out=None):
    """Write the module for *names* at *size* px to *out*; return its DATA length."""
    check_source(source, size)
    masks = [alpha_mask(find_icon(source, n, size), size) for n in names]
    total = sum(len(m) for m in masks)
    if budget is not None and total > budget:
        raise IconError(
            "%d icons at %d px need %d bytes of DATA, over the budget of %d. Drop %d icon(s) "
            "from the list or raise --budget."
            % (len(names), size, total, budget, -(-(total - budget) // (size * size)))
        )
    text = render(size, names, masks)
    with open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    if license_out:
        lic = os.path.join(source, "LICENSE")
        if not os.path.isfile(lic):
            raise IconError("%r has no LICENSE file to copy; it is not a full material-design-icons checkout" % source)
        shutil.copyfile(lic, license_out)
    return total


def main(argv=None):
    p = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    p.add_argument("source", help="a material-design-icons checkout (required; there is no default)")
    p.add_argument("--size", type=int, default=24, help="icon size in px (default 24)")
    p.add_argument("--names", help="comma-separated Material icon names")
    p.add_argument("--names-file", help="a file of names, one per line; # starts a comment")
    p.add_argument("--out", required=True, help="the module to write")
    p.add_argument("--budget", help="fail if DATA is larger, e.g. 72k")
    p.add_argument("--copy-license", metavar="DEST", help="also copy the source's LICENSE to DEST")
    a = p.parse_args(argv)
    try:
        budget = parse_budget(a.budget) if a.budget else None
        names = read_names(a.names_file, a.names)
        total = build(a.source, a.size, names, a.out, budget, a.copy_license)
    except IconError as e:
        print("make_icons: %s" % e, file=sys.stderr)
        return 1
    print("%s: %d icons, %d px, %d bytes of DATA" % (a.out, len(names), a.size, total))
    return 0


if __name__ == "__main__":
    sys.exit(main())
