"""PyDevices Jupyter CLI Runner (jupyter.py)

Drop-in CLI wrapper matching the MicroPython / CPython CLI interface
(-c / -m / <filename> / -i / -X ...).

Generates a standalone Jupyter notebook (.ipynb) from a target script,
command, or module and launches it in JupyterLab / Jupyter Notebook,
automatically opening the host system's default browser.

Agnostic of the PyDevices ecosystem — works on any Python script with
standard Jupyter requirements installed.

Usage:
  jupyter.py script.py [args...]
  jupyter.py -c "import math; print(math.pi)"
  jupyter.py -m my_module
  jupyter.py -i
  jupyter.py script.py --generate-only -o notebook.ipynb
  jupyter.py script.py --execute
"""

from __future__ import annotations

import argparse
import datetime
import json
import os
import pathlib
import re
import shutil
import subprocess
import sys
from typing import Any, Dict, List, Optional

VERSION = "0.1.0"
DEFAULT_PORT = 8888


def is_wsl() -> bool:
    if os.environ.get("WSL_DISTRO_NAME"):
        return True
    try:
        with open("/proc/version", "r") as f:
            return "microsoft" in f.read().lower()
    except OSError:
        return False


def open_browser(url: str) -> bool:
    """Open URL in the host system's default web browser (handles Linux, macOS, Windows, WSL)."""
    # 1. WSL: delegate to Windows default browser
    if is_wsl():
        # Try wslview first if available
        if shutil.which("wslview"):
            try:
                subprocess.Popen(["wslview", url])
                return True
            except Exception:
                pass
        # Try powershell.exe Start-Process
        powershell_exe = shutil.which("powershell.exe") or "/mnt/c/WINDOWS/system32/WindowsPowerShell/v1.0/powershell.exe"
        if os.path.exists(powershell_exe):
            try:
                subprocess.Popen([powershell_exe, "-NoProfile", "-Command", f"Start-Process '{url}'"])
                return True
            except Exception:
                pass
        # Try cmd.exe /c start
        cmd_exe = shutil.which("cmd.exe") or "/mnt/c/WINDOWS/system32/cmd.exe"
        if os.path.exists(cmd_exe):
            try:
                subprocess.Popen([cmd_exe, "/c", "start", "", url.replace("&", "^&")])
                return True
            except Exception:
                pass

    # 2. macOS
    if sys.platform == "darwin":
        try:
            subprocess.Popen(["open", url])
            return True
        except Exception:
            pass

    # 3. Native Windows
    if sys.platform == "win32":
        try:
            os.startfile(url)
            return True
        except Exception:
            pass

    # 4. Standard Linux with xdg-open
    if shutil.which("xdg-open"):
        try:
            subprocess.Popen(["xdg-open", url])
            return True
        except Exception:
            pass

    # 5. Fallback to Python webbrowser module
    try:
        import webbrowser
        return webbrowser.open(url)
    except Exception:
        return False


def build_notebook_json(
    title: str,
    code: str,
    script_args: Optional[List[str]] = None,
    script_name: Optional[str] = None,
) -> Dict[str, Any]:
    """Generate a valid Jupyter Notebook format 4.5 dictionary."""
    code_lines: List[str] = []

    # Inject sys.argv only if extra script arguments were provided
    if script_args:
        argv_list = [script_name or "notebook.ipynb"] + list(script_args)
        code_lines.append("import sys\n")
        code_lines.append(f"sys.argv = {argv_list!r}\n\n")

    # Format source lines ensuring proper newline termination
    raw_lines = code.splitlines(keepends=True)
    if not raw_lines:
        raw_lines = ["\n"]
    code_lines.extend(raw_lines)

    now_iso = datetime.datetime.now().strftime("%Y-%m-%d %H:%M:%S")
    markdown_lines = [
        f"# {title}\n",
        "\n",
        f"Generated by `jupyter.py` on {now_iso}.\n",
        "\n",
        "**Run:** Shift+Enter or Run All Cells to execute.\n",
    ]

    cells = [
        {
            "cell_type": "markdown",
            "id": "header",
            "metadata": {},
            "source": markdown_lines,
        },
        {
            "cell_type": "code",
            "id": "code_entry",
            "metadata": {},
            "execution_count": None,
            "outputs": [],
            "source": code_lines,
        },
    ]

    return {
        "nbformat": 4,
        "nbformat_minor": 5,
        "metadata": {
            "kernelspec": {
                "display_name": "Python 3 (ipykernel)",
                "language": "python",
                "name": "python3",
            },
            "language_info": {
                "name": "python",
                "version": sys.version.split()[0],
            },
        },
        "cells": cells,
    }


def find_jupyter_cmd(prefer_classic: bool = False) -> Optional[List[str]]:
    """Locate the jupyter executable or python module."""
    py = sys.executable

    if not prefer_classic:
        which_lab = shutil.which("jupyter-lab")
        if which_lab:
            return [which_lab]
        try:
            res = subprocess.run(
                [py, "-m", "jupyterlab", "--version"],
                capture_output=True,
                check=False,
            )
            if res.returncode == 0:
                return [py, "-m", "jupyterlab"]
        except Exception:
            pass

    which_nb = shutil.which("jupyter-notebook")
    if which_nb:
        return [which_nb]
    try:
        res = subprocess.run(
            [py, "-m", "notebook", "--version"],
            capture_output=True,
            check=False,
        )
        if res.returncode == 0:
            return [py, "-m", "notebook"]
    except Exception:
        pass

    which_jupyter = shutil.which("jupyter")
    if which_jupyter:
        subcmd = "notebook" if prefer_classic else "lab"
        return [which_jupyter, subcmd]

    return None


def execute_notebook_headless(nb_path: pathlib.Path, verbose: int = 0) -> int:
    """Execute all cells in a notebook headlessly via jupyter nbconvert."""
    py = sys.executable
    which_nbconvert = shutil.which("jupyter-nbconvert")
    cmd: List[str] = []
    if which_nbconvert:
        cmd = [which_nbconvert]
    else:
        cmd = [py, "-m", "nbconvert"]

    cmd.extend([
        "--to", "notebook",
        "--execute",
        "--inplace",
        str(nb_path),
    ])

    if verbose:
        print(f"jupyter.py: executing headlessly: {' '.join(cmd)}", file=sys.stderr)

    try:
        res = subprocess.run(cmd, capture_output=True, text=True, check=False)
        if res.returncode != 0:
            print(f"jupyter.py: execution error:\n{res.stderr}", file=sys.stderr)
            return res.returncode

        with open(nb_path, "r", encoding="utf-8") as f:
            data = json.load(f)
        for cell in data.get("cells", []):
            for out in cell.get("outputs", []):
                if "text" in out:
                    text = "".join(out["text"])
                    sys.stdout.write(text)
                elif "data" in out and "text/plain" in out["data"]:
                    text = "".join(out["data"]["text/plain"])
                    sys.stdout.write(text + "\n")
        sys.stdout.flush()
        return 0
    except FileNotFoundError:
        print(
            "jupyter.py: error: 'jupyter-nbconvert' not found for headless execution.\n"
            "  Please install with: pip install nbconvert",
            file=sys.stderr,
        )
        return 1


def build_arg_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        prog="jupyter.py",
        description="PyDevices Jupyter CLI runner (MicroPython CLI parity).",
        add_help=False,
    )
    parser.add_argument("-h", "--help", action="store_true", help="show this help message and exit")
    parser.add_argument("--version", action="store_true", help="show version information and exit")
    parser.add_argument("-v", "--verbose", action="count", default=0, help="verbose output (can be specified multiple times)")
    parser.add_argument("-i", "--repl", action="store_true", help="interactive mode (open empty/interactive notebook session)")
    parser.add_argument("-c", dest="command", help="program passed in as string")
    parser.add_argument("-m", dest="module", help="run library module as a script")
    parser.add_argument("-O", dest="optimize", nargs="?", const="1", help="accepted for MicroPython/CPython parity (no-op)")
    parser.add_argument("-X", dest="x_opt", action="append", default=[], help="implementation specific options (accepted for MicroPython parity)")

    # Jupyter specific flags
    parser.add_argument("-o", "--output", help="destination path for generated .ipynb file")
    parser.add_argument("-p", "--port", type=int, default=DEFAULT_PORT, help=f"Jupyter server port (default: {DEFAULT_PORT})")
    parser.add_argument("--no-browser", action="store_true", help="start server without automatically opening browser")
    parser.add_argument("--generate-only", "--no-server", action="store_true", dest="generate_only", help="generate .ipynb on disk and exit without starting server")
    parser.add_argument("--execute", "--run", action="store_true", dest="execute", help="execute notebook headlessly and print outputs")
    parser.add_argument("--notebook", "--classic", action="store_true", dest="classic", help="prefer classic Jupyter Notebook over JupyterLab")

    # Positional script
    parser.add_argument("script", nargs="?", help="Python script file to execute")
    return parser


def main(argv: Optional[List[str]] = None) -> int:
    parser = build_arg_parser()
    args, unknown = parser.parse_known_args(argv)
    script_args = unknown

    if args.help:
        parser.print_help()
        print("\nMicroPython compatibility notes:")
        print("  -c <cmd> | -m <mod> | <filename> are mutually exclusive.")
        print("  -O and -X options are accepted for CLI parity.")
        print("  Generated notebooks run against the selected Python 3 kernel.")
        return 0

    if args.version:
        print(f"PyDevices jupyter.py version {VERSION}")
        jupyter_cmd = find_jupyter_cmd(prefer_classic=args.classic)
        if jupyter_cmd:
            print(f"Jupyter command: {' '.join(jupyter_cmd)}")
        else:
            print("Jupyter server: not found (install with 'pip install jupyterlab')")
        return 0

    # Validate mutually exclusive entrypoints
    n_entry = sum(1 for x in (args.command, args.module, args.script) if x)
    if n_entry > 1:
        print("jupyter.py: error: use only one of -c, -m, or <filename>", file=sys.stderr)
        return 1

    title = "Interactive Notebook"
    code = ""
    script_name: Optional[str] = None
    output_filename = "notebook.ipynb"

    if args.command is not None:
        title = "Command One-Liner"
        code = args.command
        script_name = "-c"
        output_filename = "run-command.ipynb"

    elif args.module:
        title = f"Module {args.module}"
        code = f"import {args.module}\n"
        script_name = f"-m {args.module}"
        slug = args.module.replace(".", "_")
        output_filename = f"run-{slug}.ipynb"

    elif args.script:
        script_path = pathlib.Path(args.script).resolve()
        if not script_path.is_file():
            print(f"jupyter.py: error: script file not found: {args.script}", file=sys.stderr)
            return 1
        title = script_path.name
        try:
            code = script_path.read_text(encoding="utf-8")
        except OSError as exc:
            print(f"jupyter.py: error reading script file: {exc}", file=sys.stderr)
            return 1
        script_name = script_path.name
        output_filename = f"{script_path.stem}.ipynb"

    elif args.repl:
        title = "Interactive Session"
        code = "# Interactive Jupyter Notebook\n"
        output_filename = "interactive.ipynb"
    else:
        # Bare invocation with no args -> interactive
        title = "Interactive Session"
        code = "# Interactive Jupyter Notebook\n"
        output_filename = "interactive.ipynb"

    dest_path = pathlib.Path(args.output) if args.output else pathlib.Path(output_filename).resolve()
    dest_path.parent.mkdir(parents=True, exist_ok=True)

    nb_json = build_notebook_json(
        title=title,
        code=code,
        script_args=script_args,
        script_name=script_name,
    )

    try:
        with open(dest_path, "w", encoding="utf-8") as f:
            json.dump(nb_json, f, indent=1)
        if args.verbose or args.generate_only:
            print(f"jupyter.py: generated notebook -> {dest_path}", file=sys.stderr)
    except OSError as exc:
        print(f"jupyter.py: error writing notebook: {exc}", file=sys.stderr)
        return 1

    if args.generate_only:
        return 0

    if args.execute:
        return execute_notebook_headless(dest_path, verbose=args.verbose)

    # Launch Jupyter server
    jupyter_cmd = find_jupyter_cmd(prefer_classic=args.classic)
    if not jupyter_cmd:
        print(
            "jupyter.py: error: Jupyter is not installed in the current environment.\n"
            "  Generated notebook is ready at: %s\n"
            "  To install JupyterLab, run: pip install jupyterlab" % dest_path,
            file=sys.stderr,
        )
        return 1

    cmd = list(jupyter_cmd)
    cmd.append(str(dest_path))
    cmd.extend(["--port", str(args.port)])
    cmd.append("--no-browser")

    if args.verbose:
        print(f"jupyter.py: launching: {' '.join(cmd)}", file=sys.stderr)

    try:
        proc = subprocess.Popen(
            cmd,
            stdout=subprocess.PIPE,
            stderr=subprocess.STDOUT,
            text=True,
            bufsize=1,
        )

        opened_browser = False
        url_pattern = re.compile(r"http://(localhost|127\.0\.0\.1):\d+/(?:lab|tree)\?token=[a-zA-Z0-9]+")

        assert proc.stdout is not None
        for line in proc.stdout:
            sys.stdout.write(line)
            sys.stdout.flush()

            if not opened_browser and not args.no_browser:
                match = url_pattern.search(line)
                if match:
                    base_url = match.group(0)
                    rel_name = dest_path.name
                    if "/lab?token=" in base_url:
                        target_url = base_url.replace("/lab?token=", f"/lab/tree/{rel_name}?token=")
                    elif "/tree?token=" in base_url:
                        target_url = base_url.replace("/tree?token=", f"/tree/{rel_name}?token=")
                    else:
                        target_url = base_url

                    open_browser(target_url)
                    opened_browser = True

        return proc.wait()
    except KeyboardInterrupt:
        return 0
    except Exception as exc:
        print(f"jupyter.py: error launching Jupyter: {exc}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    sys.exit(main())
